/**
 * Generates `src/contracts/abis.ts` from the Foundry build output so the app and the
 * deployed bytecode can never drift apart. Run after every contract change: `npm run contracts:abi`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ARTIFACTS_DIR = resolve(import.meta.dirname, "../contracts/out");
const OUTPUT_FILE = resolve(import.meta.dirname, "../src/contracts/abis.ts");

const CONTRACTS = [
  { artifact: "GuaranteeEscrow.sol/GuaranteeEscrow.json", exportName: "guaranteeEscrowAbi" },
  { artifact: "StockOracle.sol/StockOracle.json", exportName: "stockOracleAbi" },
  { artifact: "MockStockToken.sol/MockStockToken.json", exportName: "mockStockTokenAbi" },
  { artifact: "MockPriceFeed.sol/MockPriceFeed.json", exportName: "mockPriceFeedAbi" },
] as const;

const sections = CONTRACTS.map(({ artifact, exportName }) => {
  const { abi } = JSON.parse(readFileSync(resolve(ARTIFACTS_DIR, artifact), "utf8"));
  return `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;`;
});

const header = "// Generated by scripts/export-abis.ts from the Foundry build output. Do not edit by hand.\n";
writeFileSync(OUTPUT_FILE, `${header}\n${sections.join("\n\n")}\n`);

console.log(`Wrote ${CONTRACTS.length} ABIs to ${OUTPUT_FILE}`);
