/**
 * Generates `src/contracts/abis.ts` from the Foundry build output so the app and the
 * deployed bytecode can never drift apart. Run after every contract change: `npm run contracts:abi`.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { loadArtifact } from "./lib/artifacts";

const OUTPUT_FILE = resolve(import.meta.dirname, "../src/contracts/abis.ts");

/** Contract name in `contracts/out` -> export name in the app. Mocks only exist on local and testnet. */
const CONTRACTS = {
  ReservationEscrow: "reservationEscrowAbi",
  StockOracle: "stockOracleAbi",
  GoalRegistry: "goalRegistryAbi",
  DemoExchange: "demoExchangeAbi",
  MockStockToken: "mockStockTokenAbi",
  MockUSDC: "mockUsdcAbi",
  MockWARS: "mockWarsAbi",
  MockPriceFeed: "mockPriceFeedAbi",
  AggregatorV3Interface: "aggregatorV3Abi",
} as const;

const sections = Object.entries(CONTRACTS).map(([contract, exportName]) => {
  const { abi } = loadArtifact(contract);
  return `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;`;
});

const header = "// Generated by scripts/export-abis.ts from the Foundry build output. Do not edit by hand.\n";
writeFileSync(OUTPUT_FILE, `${header}\n${sections.join("\n\n")}\n`);

console.log(`Wrote ${sections.length} ABIs to ${OUTPUT_FILE}`);
